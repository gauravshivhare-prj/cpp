#include <iostream>
using namespace std;

int main()
{
    // variables in c++
    int a=10;  // integer variable
    float b=20.5;  // float variable
    char c='A';  // character variable
    double d=30.123456789;  // double variable

    cout << "Integer: " << a << endl;
    cout << "Float: " << b << endl;
    cout << "Character: " << c << endl;
    cout << "Double: " << d << endl;

    return 0;
}